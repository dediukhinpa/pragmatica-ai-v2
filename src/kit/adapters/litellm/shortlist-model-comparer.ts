/**
 * Сравнение кандидатов моделью через переданный шлюз (сборка передаёт `PseudonymizingModelGateway`)
 * с алиасом агента «Поиск поставщика». Факты уходят только в запрос; в ответ, ошибки и журналы они
 * не попадают.
 */
export class ModelShortlistComparer implements ShortlistComparer {
  constructor(
    private readonly models: ModelGateway,
    /** Алиас модели агента «Поиск поставщика» (`ORDER_CALC_MODEL`). */
    private readonly model: string,
  ) {}

  async compare(
    facts: ShortlistCompareFacts,
    options: ShortlistCompareOptions,
  ): Promise<RawCompareAnswer> {
    options.signal.throwIfAborted();
    const response = await this.models.complete(
      {
        model: this.model,
        threadId: SHORTLIST_COMPARE_THREAD_ID,
        maxTokens:
          COMPARE_ANSWER_BASE_TOKENS +
          COMPARE_ANSWER_TOKENS_PER_CANDIDATE * facts.candidates.length,
        messages: [
          { role: 'system', content: SYSTEM_PROMPT },
          {
            role: 'user',
            content:
              `Кандидатов: ${facts.candidates.length}. Кандидаты (JSON):\n` +
              `<<<${JSON.stringify(facts)}>>>`,
          },
        ],
      },
      { signal: options.signal },
    );
    return { text: response.content, truncated: response.stopReason === 'max_tokens' };
  }
}
