/** JSON-объект из текста ответа (модель могла обернуть его в блок кода). */
function extractJson(text: string): unknown {
  const start = text.indexOf('{');
  const end = text.lastIndexOf('}');
  if (start === -1 || end <= start) return null;
  try {
    return JSON.parse(text.slice(start, end + 1));
  } catch {
    return null;
  }
}

/** Проверка строк прайсов моделью: позиции и названия идут через шлюз псевдонимизации. */
export class ModelPriceRelevanceChecker implements PriceRelevanceChecker {
  constructor(
    private readonly models: ModelGateway,
    /** Алиас модели агента «Поиск поставщика» (`ORDER_CALC_MODEL`). */
    private readonly model: string,
  ) {}

  async check(input: PriceRelevanceInput, options: PriceRelevanceOptions): Promise<unknown> {
    options.signal.throwIfAborted();
    const response = await this.models.complete(
      {
        model: this.model,
        threadId: PRICE_RELEVANCE_THREAD_ID,
        maxTokens: ANSWER_MAX_TOKENS,
        messages: [
          { role: 'system', content: SYSTEM_PROMPT },
          { role: 'user', content: `Позиции и названия (JSON):\n<<<${JSON.stringify(input)}>>>` },
        ],
      },
      { signal: options.signal },
    );
    return extractJson(response.content);
  }
}
