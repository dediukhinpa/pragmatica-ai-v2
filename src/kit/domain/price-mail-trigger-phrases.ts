/**
 * Данные словаря «письмо о ценах» (ТЗ заказчика, п. 7.2): классы слов и правила, из которых
 * `price-mail-triggers.ts` строит поиск. Чтобы добавить признак, правится только этот файл.
 *
 * Запись слова в классе:
 *  - `слово` - токен письма должен совпасть целиком («цен» не находит «центр»);
 *  - `основа*` - любое окончание после основы («повыш*» находит «повышение», «повышаем»).
 * Слова пишутся строчными, `ё` заменяется на `е`: так же нормализуется текст письма.
 *
 * Правило срабатывает, когда слово класса `anchor` стоит рядом (в окне из нескольких токенов,
 * в любом порядке) со словом класса `partner`; без `partner` достаточно одного слова `anchor`.
 */

/** Части письма, где ищется правило. */
