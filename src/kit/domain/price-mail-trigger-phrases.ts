/** Правило в данных: поля письма, класс-якорь и (необязательно) класс-партнёр. */
interface PriceMailRuleSpec {
  fields: readonly PriceMailField[];
  anchor: readonly PriceMailWordClass[];
  partner?: readonly PriceMailWordClass[];
}

/** Описание триггера в данных. */
export interface PriceMailTriggerSpec {
  id: PriceMailTriggerId;
  /** Подпись для сообщения сотруднику. */
  label: string;
  rules: readonly PriceMailRuleSpec[];
  /**
   * Фразы-образцы: каждая обязана находиться этим триггером (проверяет тест словаря). Служат
   * и перечнем признаков для людей, и защитой от случайной потери фразы при правке классов.
   */
  examples: readonly string[];
}

