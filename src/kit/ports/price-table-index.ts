/**
 * Что известно о файле по уже разобранному тексту в базе знаний:
 * `absent` - файла нет в базе (текста нет: фото, скан, не разобран);
 * `not_table` - в базе есть, но таблицей цен он не выглядит;
 * `table` - в начале текста таблица цен.
 */
export type PriceTableVerdict = 'absent' | 'not_table' | 'table';

/** Признак «таблица цен» по пути файла (путь от корня диска, как `source` в базе знаний). */
export interface PriceTableIndex {
  /**
   * Вердикт для каждого пути из списка; запрос к хранилищу идёт пачками, а не по файлу.
   * В результате есть запись для каждого переданного пути.
   */
  verdicts(paths: readonly string[]): Promise<Map<string, PriceTableVerdict>>;
}
