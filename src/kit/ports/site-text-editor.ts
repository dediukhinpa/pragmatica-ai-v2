/**
 * Редактор текстов выгрузочной таблицы сайта (этап 225): сжатие описания до предела и
 * исправление орфографии одним вызовом модели. Включается флагом `SITE_TEXT_EDITOR_ENABLED`
 * (по умолчанию выключен): без него орфография не правится, а длинное описание возвращается
 * агенту на сокращение.
 */

/** Один текст на правку. */
export interface SiteTextEditRequest {
  /** Идентификатор в рамках пакета: по нему ответ сопоставляется с запросом. */
  id: string;
  /** Исходный текст (пробелы уже приведены кодом). */
  text: string;
  /** Предел длины результата, знаков. */
  maxChars: number;
  /** Текст длиннее предела: его нужно сжать, а не только поправить орфографию. */
  compress: boolean;
  /** Прошлый вариант модели, который не подошёл по длине: сжать его дальше. */
  draft?: string | undefined;
  /** Почему прошлый вариант отклонён кодом (длина, изменённые числа и т.п.). */
  problem?: string | undefined;
}

/** Правка одного текста. */
export interface SiteTextEditResult {
  id: string;
  text: string;
}

/** Параметры вызова. */
export interface SiteTextEditOptions {
  /** Сигнал отмены хода агента. */
  signal: AbortSignal;
  /**
   * Тред агента (`ToolContext.threadId`). Токены псевдонимизации стабильны в рамках треда, поэтому
   * запрос идёт в тред хода, а не в общий: тексты разных клиентов в одном треде смешивались бы.
   */
  threadId: string;
}

/**
 * Пакетная правка текстов. Реализация, которая отправляет тексты внешней модели, обязана
 * пропускать их через псевдонимизацию (`PseudonymizingModelGateway`) и не писать тексты в
 * журналы. Результат НЕ доверенный: вызывающий код сам проверяет длину и инварианты (числа,
 * артикулы, единицы, токены маски); ошибки — обычные исключения.
 */
export interface SiteTextEditor {
  edit(
    requests: readonly SiteTextEditRequest[],
    options: SiteTextEditOptions,
  ): Promise<SiteTextEditResult[]>;
}
