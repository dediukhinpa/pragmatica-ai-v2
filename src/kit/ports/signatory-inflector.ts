/**
 * Склонение подписанта договора на РФ (формула «в лице генерального директора Иванова И. И.»).
 * Модель видит ФИО токеном и просклонять его не может, поэтому склоняет сервис по настоящему
 * значению.
 */
export interface SignatoryInflector {
  /**
   * Должность и ФИО в родительном падеже: «генерального директора Дудоровой Марины Евгеньевны».
   * null - словарь не разобрал уверенно (инициалы, редкая фамилия): тогда спрашивают сотрудника.
   */
  signatoryGenitive(position: string, fullName: string): Promise<string | null>;
}
