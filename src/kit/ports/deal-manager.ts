/**
 * Менеджер, ведущий сделку («От Заказчика» в договоре). Персональные данные: возвращаются только
 * коду сборки договора, модели не передаются, в журналы, задания и аудит не пишутся.
 */
export interface DealManager {
  /** ФИО целиком («Фамилия Имя Отчество»); null - в карточке сотрудника имени нет. */
  name: string | null;
  /** Телефон (рабочий, затем мобильный, затем личный); null - не указан. */
  phone: string | null;
  /** Почта; null - не указана. */
  email: string | null;
}

/** Чтение ответственного за сделку. */
export interface DealManagerReader {
  /**
   * Менеджер сделки по ссылке. null - явное «нет»: сделки нет или недоступна, ответственный не
   * назначен либо его карточка не найдена (агент должен спросить сотрудника). Пустые поля
   * найденного менеджера - тоже null в соответствующем поле. Сбой портала - `DomainError`
   * (`external_failure`).
   */
  findDealManager(dealRef: string): Promise<DealManager | null>;
  /**
   * Контакт сотрудника портала по его id (автор запроса, когда у документа нет сделки).
   * null - сотрудника нет, id не числовой или карточка недоступна. Сбой портала -
   * `DomainError` (`external_failure`). Данные те же персональные, что у менеджера сделки.
   */
  findUser(userId: string): Promise<DealManager | null>;
}
