/**
 * Чтение компаний-поставщиков из CRM (этап 221): источник создания и дополнения карточек
 * поставщиков. Порт только читает; запись в CRM не предусмотрена. Что считать «поставщиком»
 * (тип компании, категория или то и другое сразу), решает настройка адаптера, а не вызывающий
 * код. Каждый признак - отдельный «проход» чтения со своим курсором (см. `CrmSuppliers.passes`).
 */

/** Контакт компании CRM: ФИО, должность, почта, телефон (любое поле может отсутствовать). */
export interface CrmSupplierContact {
  fullName?: string;
  position?: string;
  email?: string;
  phone?: string;
}

/**
 * Компания-поставщик CRM. Значения как в CRM: проверку (контрольная сумма ИНН, формат сайта и
 * телефона) делает потребитель, адаптер её не навязывает.
 */
export interface CrmSupplierCompany {
  /** Идентификатор компании в CRM (строка из цифр). */
  id: string;
  /** Название компании. */
  title: string;
  /** Время последнего изменения (ISO 8601, UTC): по нему идёт курсор. */
  modifiedAt: string;
  inn?: string;
  kpp?: string;
  ogrn?: string;
  legalAddress?: string;
  websites: string[];
  emails: string[];
  phones: string[];
  contacts: CrmSupplierContact[];
  /**
   * Компания из «запаса по времени» перед курсором: её время изменения не позже курсора, и
   * читается она повторно на случай запоздавшей записи в CRM. Не занимает предел порции и не
   * двигает курсор; для остальных компаний поля нет.
   */
  replayed?: boolean;
}

const MS_PER_MINUTE = 60_000;
const CURSOR_MARGIN_MINUTES = 10;

/**
 * Запас по времени перед курсором: запись в CRM могла стать видимой позже, чем получила время
 * изменения (долгая транзакция, расхождение часов портала), и чтение строго после курсора её
 * бы навсегда пропустило. Повторное чтение безопасно: запись карточки идемпотентна.
 */
export const CRM_SUPPLIERS_CURSOR_MARGIN_MS = CURSOR_MARGIN_MINUTES * MS_PER_MINUTE;

/**
 * Позиция чтения: последняя обработанная компания. Порядок списка - по времени изменения, затем
 * по id; компании с тем же временем, но меньшим или равным id, уже обработаны.
 */
export interface CrmSuppliersCursor {
  modifiedAt: string;
  id: string;
}

/** Запрос очередной порции компаний после курсора. */
export interface CrmSuppliersQuery {
  /**
   * Проход (один из `CrmSuppliers.passes`), по которому читать. Не задан - первый проход: у
   * адаптера с одним признаком он единственный. Курсор `after` принадлежит этому проходу.
   */
  pass?: string | undefined;
  /** После какой компании читать; null - с начала. */
  after: CrmSuppliersCursor | null;
  /** Сколько компаний вернуть не больше. */
  limit: number;
  signal?: AbortSignal | undefined;
}

/** Порция компаний в порядке курсора. */
export interface CrmSuppliersPage {
  companies: CrmSupplierCompany[];
  /** За этой порцией в CRM есть ещё компании (читать дальше с курсора просмотра). */
  hasMore: boolean;
  /**
   * Последняя просмотренная строка списка после курсора запроса, включая отброшенные (не
   * поставщики, строки без даты): курсор можно двигать до неё, не перечитывая их каждый раз.
   * null - после курсора не просмотрено ничего.
   */
  viewedUntil: CrmSuppliersCursor | null;
  /**
   * Сколько просмотренных строк не имели признака «поставщик». Не ноль - портал, скорее всего,
   * проигнорировал фильтр: потребитель сообщает об этом владельцу.
   */
  markerMismatch: number;
}

/**
 * Компании-поставщики CRM. Поставщик - компания, подходящая под ЛЮБОЙ из настроенных признаков
 * (объединение): каждому признаку соответствует свой проход чтения. Проходы идут в порядке
 * `passes`; компания, подходящая под несколько признаков, отдаётся только первым из подходящих
 * проходов (последующие её пропускают, продвигая свой курсор), поэтому дублей между проходами
 * нет и суточный предел потребителя на неё не тратится дважды.
 *
 * Ошибка недоступности портала - `DomainError('external_failure')`
 * (повторяемая), нехватка прав вебхука - `ExternalAccessDeniedError`.
 */
export interface CrmSuppliers {
  /**
   * Идентификаторы проходов в порядке чтения (не пусто). Идентификатор включает значение
   * признака (например, `category-8`): курсор одного признака не применяется к другому.
   */
  readonly passes: readonly string[];
  listSupplierCompanies(query: CrmSuppliersQuery): Promise<CrmSuppliersPage>;
}
