/**
 * Абзац промпта агента прайсов: правка цены в файле сотрудника сразу, без вопроса о поставщике,
 * и как понимать «на слайде N» (этап 9p, решение владельца 22.11.2026). Подключается опцией
 * декларации `priceEditFirst` (`PRICE_EDIT_FIRST_ENABLED`); без неё промпт прежний.
 */
const PRICE_EDIT_FIRST_HEAD = `

Правка цены в файле, который прислал сотрудник («на слайде 11 цену 680 замени на 700», «в
строке с артикулом A1 поставь 150»). Правь СРАЗУ: не спрашивай поставщика до правки, не
разбирай файл как прайс поставщика (не нужны stagePriceRows, supplierId, fileHash) и не проси
прислать файл заново. Порядок:
 1) Файл: path из сообщения сотрудника (listIntakeFiles покажет файлы чата). Прочитай нужное
    место через readPriceFile. У каждой таблицы в заголовке стоит её место («Таблица 5:
    «Слайд 11»», «Страница 3», лист xlsx) и то же лежит в tablePlaces. «На слайде N» - это
    таблица с меткой «Слайд N» (в тексте pptx заголовки «## Слайд N»), «на странице N» и «стр. N»
    - «Страница N» (pdf; у docx номер страницы считается по фактической вёрстке). Если у файла
    pagesNote «страница не определена», номера страниц у него нет: не придумывай номер и не
    ссылайся на него, попроси сотрудника назвать позицию или артикул.
 2) editPriceInFile: path, edits [{oldPrice, newPrice, slide или page или sheet, при
    необходимости row/rowText}]. oldPrice - цена, которую назвал сотрудник; код сам найдёт
    ячейку и сверит старую цену. supplierId передавай, только если поставщик точно найден в
    базе. Исходный файл не меняется, исправленная копия сразу уходит в этот чат.
 3) Единственный допустимый вопрос ДО правки: status=ambiguous (цена встречается несколько раз
    и сотрудник не указал место). Задай ОДИН короткий вопрос с вариантами из variants (слайд или
    страница и строка), без других вопросов, и после ответа повтори вызов с уточнением.
    status=not_found - скажи, что такой цены на этом месте нет, спроси где искать; цену не
    угадывай. Отказы pdf и unsupported_format - как у editPricesInSourceFile: назови причины,
    xlsx-копия только с согласия сотрудника.
 4) После status=sent в ТОМ ЖЕ ответе: что изменено (из changes: было -> стало, место); если
    supplier=null - вопрос «это поставщик X?» (X из searchSuppliers по названию файла или
    тексту, если он очевиден) либо «как называется поставщик?»; вопрос «обновить цены этих
    позиций в базе?». Ничего в базу не пиши, пока сотрудник явно не сказал «да».
`;

/** Пункт 5 без прямой записи в базу (9p): цены со слов сотрудника принимаются предложением. */
const ITEM_PROPOSAL =
` 5) Ответ сотрудника на следующем ходе: getPendingPriceEdit покажет, что было изменено.
    «Да» (и поставщик, если его назвали): найди поставщика (lookupSupplierInBase,
    searchSuppliers); нет в базе - предложи завести карточку прежним путём (карточку создаёт
    recordSupplierLookupDecision только после его «да», нужны права); без поставщика в базу не
    пиши. Затем прежний
    путь записи цен со слов сотрудника: recordEmployeePriceUpdates (название и артикул из
    rowCells, price = newPrice), previewPriceChanges и дальше как в пункте в) источников; после
    записи closePendingPriceEdit(saved). Результат скажи как есть: цены с диска пишутся в базу
    сразу, а цены со слов сотрудника commitPriceImport принимает предложением
    (proposed_not_written): в базу они попадут, когда появятся на диске, - так и скажи, не
    говори «записано в базу». «Нет», «не надо» - closePendingPriceEdit(declined),
    в базу ничего не пишется. Если сотрудник не ответил, база остаётся прежней: ожидание живёт
    сутки в этом чате и сбрасывается новой правкой.
`;

