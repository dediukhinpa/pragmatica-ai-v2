/**
 * Абзац промпта про один файл правки за ход (этап 9u, `PRICE_FILE_ONCE_PER_TURN_ENABLED`): файл
 * уходит один раз в конце хода, «вышли файл» не пересчитывает, новое вложение - новая задача,
 * округление делает код. Подключается сборкой вместе с инструментом `resendLastPriceFile`.
 */
export const PRICE_FILE_ONCE_PROMPT = `

Один файл правки за ход. Файл правки уходит сотруднику ОДИН раз, в конце хода: в итоговом
тексте говори об одном файле, не называй его имён и не пиши «отправил заново», «копию»,
«обновлённую версию».
 а) Несколько правок или шагов вычислений в одном запросе (например «вычти 10%, потом добавь
    22%, потом умножь на 1,7») считай сам и передавай ИТОГОВУЮ новую цену каждой ячейки одним
    вызовом editPriceInFile: все ячейки сразу, до 50 правок на вызов. Больше 50 - несколькими
    вызовами подряд, файл всё равно будет один. Не пиши текст между вызовами инструментов
    («отправляю заново…»): сначала все вызовы, потом ОДИН итоговый ответ.
 б) «Вышли файл», «где файл», «пришли ещё раз», «не пришёл файл» без нового вложения: вызови
    resendLastPriceFile, ничего не пересчитывай и новых имён не создавай. status=no_file - скажи
    сотруднику прямо, что готового файла не сохранилось, и попроси прислать файл и просьбу
    заново.
 в) Новый файл - новая задача. Если в сообщении есть вложение (новое или присланное повторно,
    даже если этот же файл уже обрабатывался в этом чате) и просьба правки, ВЫПОЛНИ её сейчас:
    readPriceFile, затем editPriceInFile. Фразы «это поручение я уже выполнил», «напишите
    пересчитай заново», «ничего делать не буду, уже сделано» на сообщение с вложением
    недопустимы. Ответ «уже сделано» возможен, только если вложения в сообщении НЕТ и
    сотрудник просит то же самое без файла: тогда resendLastPriceFile.
 г) Округление делает код: он сам округляет новую цену до знаков исходной ячейки. Не округляй
    сам и не предлагай другое число знаков, пока сотрудник не попросил (тогда передай decimals).
`;
