/** `ГГГГ-ММ-ДД` или `ГГГГ-ММ` (только месяц) -> дата. */
function toDate(text: string): PriceFileDate {
  const [year, month, day] = text.split('-').map(Number);
  return { year: year as number, month: month as number, day: day ?? null };
}

describe('реальные названия прайсов: дата и тип (now = 2026-10-22, Europe/Moscow)', () => {
  test('в таблице все 132 имени, без повторов', () => {
    expect(CORPUS).toHaveLength(132);
    expect(new Set(CORPUS.map(([name]) => name)).size).toBe(132);
  });

  for (const [name, expected] of CORPUS) {
    test(name, () => {
      const date = parsePriceFileDate(name, NOW, TZ, NOW);
      if (expected === NO_DATE || expected === NOT_PRICE) {
        expect(date).toBeNull();
        expect(classifyPriceFileName(name)).toBe(expected === NOT_PRICE ? 'not_price' : 'price');
      } else {
        expect(date).toEqual(toDate(expected));
        // Ни одна найденная дата не из будущего (текущий месяц - октябрь 2026, до 22-го).
        const found = date as PriceFileDate;
        const monthIndex = found.year * MONTHS_IN_YEAR + found.month;
        expect(monthIndex).toBeLessThanOrEqual(NOW_MONTH_INDEX);
        if (found.year === NOW_YEAR && found.month === NOW_MONTH && found.day !== null) {
          expect(found.day).toBeLessThanOrEqual(NOW_DAY);
        }
      }
    });
  }

  test('итоги: 121 с датой, 7 прайсов без даты, 4 не прайса', () => {
    const counts = { dated: 0, noDate: 0, notPrice: 0 };
    for (const [, expected] of CORPUS) {
      if (expected === NO_DATE) counts.noDate += 1;
      else if (expected === NOT_PRICE) counts.notPrice += 1;
      else counts.dated += 1;
    }
    expect(counts).toEqual({ dated: 121, noDate: 7, notPrice: 4 });
  });

  test('без now записи без года даты не дают, остальные имена разбираются как раньше', () => {
    expect(parsePriceFileDate('Прайс_Шевроны-наклейки_13.10.xlsx')).toBeNull();
    expect(parsePriceFileDate('Прайс_Кольчугинский_01_07.xlsx')).toBeNull();
    expect(parsePriceFileDate('Ильинская Мануфактура_прайс_15.09.2025.xlsx')).toEqual(
      toDate('2025-09-15'),
    );
  });
});
