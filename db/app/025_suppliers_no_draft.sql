-- Миграция 042: карточки поставщиков без черновиков (этап 240, решение владельца 09.11.2026).
-- Признака черновика больше нет: ядро не читает и не пишет `suppliers.is_draft`, все карточки
-- боевые. Эта миграция приводит данные в соответствие: у старых карточек-черновиков (создал
-- агент прайсов по шапке файла) флаг сбрасывается, и они остаются в базе как обычные. Ничего не
-- удаляется: ни карточки, ни цены, ни заметки (в заметке остаётся строка «Не проверено: ...»,
-- это история происхождения данных). Частичный индекс по черновикам больше не нужен.
-- Столбец `is_draft` НЕ удаляется: прежний образ ядра, если его придётся вернуть, читает его в
-- каждом запросе карточки; удалять столбец можно отдельной миграцией после отказа от отката.
-- Идемпотентна: UPDATE затрагивает только строки с флагом, DROP INDEX IF EXISTS. Код этого
-- релиза игнорирует флаг и сам по себе работает и без миграции, но `/ready` ждёт версию схемы
-- 042 (`EXPECTED_SCHEMA_VERSION`), поэтому миграция накатывается до выкладки образа.
-- Накатывает владелец на бою (красная зона): бэкап БД -> миграция -> код.
-- Откат: старые черновики потеряли признак и по данным не восстанавливаются; из бэкапа:
--   UPDATE suppliers SET is_draft = true WHERE id IN (<id из бэкапа>);
--   CREATE INDEX IF NOT EXISTS suppliers_draft_idx ON suppliers (id) WHERE is_draft;
--   DELETE FROM schema_migrations WHERE version = '042_suppliers_no_draft';

UPDATE suppliers SET is_draft = false WHERE is_draft;

DROP INDEX IF EXISTS suppliers_draft_idx;
